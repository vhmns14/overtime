// Full demo tour with screenshots at each key moment (README + mockup comparison).
// Usage: node scripts/tour.mjs <baseUrl> <outDir> <width> <height>
import { chromium } from "@playwright/test";
process.env.LD_LIBRARY_PATH = ["/workspace/work/.pw-libs", process.env.LD_LIBRARY_PATH].filter(Boolean).join(":");
const [base = "http://127.0.0.1:8787", out = "shots", w = "1440", h = "900"] = process.argv.slice(2);
const mobile = +w < 600;
const browser = await chromium.launch({ executablePath: "/workspace/work/.pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell" });
const page = await browser.newPage({ viewport: { width: +w, height: +h }, isMobile: mobile, hasTouch: mobile, deviceScaleFactor: mobile ? 2 : 1 });
const errors = [];
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
page.on("pageerror", (e) => errors.push(String(e)));
const tag = mobile ? "m" : "d";
const shot = (n) => page.screenshot({ path: `${out}/${tag}-${n}.png` });
const gate = mobile ? "#mobile-approval:not([hidden])" : "#approval:not([hidden])";
const approve = mobile ? "#mobile-approval [data-act=approve]" : "#approval [data-act=approve]";
await page.goto(`${base}/?speed=0.35`);
await page.waitForTimeout(1200);
await shot("0-ready");
await page.click("#run-btn");
await page.waitForSelector(gate, { timeout: 60000 });
await page.waitForTimeout(400);
await shot("1-plan-gate");
await page.click(approve);
await page.waitForTimeout(1800);
await shot("2-meeting");
await page.waitForFunction(() => document.querySelector('[data-step="code"]')?.classList.contains("active"), null, { timeout: 60000 });
await page.waitForTimeout(2500);
await shot("3-coding");
await page.waitForSelector(gate, { timeout: 90000 });
await page.waitForTimeout(500);
await shot("4-review-gate");
await page.click(approve);
await page.waitForSelector(gate, { timeout: 90000 });
await page.waitForTimeout(500);
await shot("5-deploy-gate");
await page.click(approve);
await page.waitForSelector("#result:not([hidden])", { timeout: 60000 });
await page.waitForTimeout(800);
await shot("6-done");
await page.click('#result [data-r="files"]');
await page.waitForTimeout(500);
await page.selectOption("[data-version]", { index: 0 });
await page.check("[data-diff]");
await page.waitForTimeout(300);
await shot("7-files-diff");
await page.click('[data-tab="preview"]');
await page.waitForTimeout(2500);
await shot("8-preview");
console.log("errors:", JSON.stringify(errors));
await browser.close();
